function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="pt-BR" className="dark">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function AuthGate() {
  const { user, isLoading, needsSetup } = useAuth();
  const location = useLocation();
  const navigate = useNavigate();

  const isPublicPage = location.pathname === "/login" || location.pathname === "/setup";

  useEffect(() => {
    if (isLoading) return;

    if (needsSetup && location.pathname !== "/setup") {
      void navigate({ to: "/setup" });
      return;
    }

    if (needsSetup === false && !user && !isPublicPage) {
      void navigate({ to: "/login" });
      return;
    }
  }, [user, isLoading, needsSetup, location.pathname, isPublicPage, navigate]);

  if (isPublicPage) {
    return <Outlet />;
  }

  if (isLoading) {
    return (
      <div className="flex min-h-screen items-center justify-center bg-background text-muted-foreground">
        <div className="flex flex-col items-center gap-2">
          <div className="size-6 animate-spin rounded-full border-2 border-primary border-t-transparent" />
          <span className="text-sm">Carregando HarborX…</span>
        </div>
      </div>
    );
  }

  if (!user) {
    return null;
  }

  return (
    <AppShell>
      <Outlet />
    </AppShell>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <AuthProvider>
        <AuthGate />
      </AuthProvider>
      <Toaster theme="dark" />
    </QueryClientProvider>
  );
}
